#!/usr/bin/env python3
"""Emit sine.a86: python3 tools/generate_sine.py > src/sine.a86."""

import math


def main():
    values = [round(2048 * math.sin(math.radians(angle))) for angle in range(91)]
    print("; Generated by tools/generate_sine.py; do not edit.")
    print("; Sine samples: round(2048*sin(degrees)), 0..90.")
    print("sine_table:")
    for start in range(0, len(values), 8):
        print("\tdw\t" + ",".join(str(value) for value in values[start:start + 8]))


if __name__ == "__main__":
    main()
