#!/usr/bin/env python3
"""Build SNIOS.SPR, SNIOSSIO.SPR, and SNIOSPIO.SPR from snios.asm using zmac.

SPR format (as loaded by CPNETLDR):
  Sector 0:      parameter record (128 bytes)
    +1: code length (2 bytes, little-endian)
    +3: data length (2 bytes, little-endian)
  Sector 1:      data sector (128 bytes, read and discarded by loader)
  Sectors 2..N+1: code (padded to 128-byte sectors)
  Following:      relocation bitmap (1 bit per code byte, MSB first)
    bit=1 means the corresponding byte is the HIGH part of a 16-bit
    address that needs the load bias added.

The relocation bitmap is generated by assembling twice at different ORGs
and comparing: any byte that differs is a relocatable address high-byte.
"""

import os
import subprocess
import sys
import math
import shutil
import datetime

ZMAC = os.path.join(os.path.dirname(__file__), '..', 'zmac', 'bin', 'zmac')
SRC = os.path.join(os.path.dirname(__file__), 'snios.asm')
OUTDIR = os.path.join(os.path.dirname(__file__), 'zout')


def generate_buildinfo(outdir):
    """Generate buildinfo.inc containing timestamp and short git commit SHA."""
    now_str = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
    repo_dir = os.path.dirname(__file__)

    git_cmd = subprocess.run(
        ['git', '-C', repo_dir, 'rev-parse', '--short', 'HEAD'],
        capture_output=True, text=True
    )
    sha = git_cmd.stdout.strip() or '????'

    dirty_cmd = subprocess.run(
        ['git', '-C', repo_dir, 'diff', '--quiet', 'HEAD', '--', '.'],
        capture_output=True
    )
    if dirty_cmd.returncode != 0:
        sha += '+'

    buildinfo_path = os.path.join(outdir, 'buildinfo.inc')
    with open(buildinfo_path, 'w') as f:
        f.write('; auto-generated by build_snios.py -- do not edit\n')
        f.write(f'\tDB\t"{now_str} {sha}"\n')

    return f"{now_str} {sha}"


def assemble(src, org, outdir, defines=None, suffix=''):
    """Assemble at given ORG, return raw binary bytes."""
    wrapper = os.path.join(outdir, f'snios_org{org:04X}{suffix}.asm')
    cim = os.path.join(outdir, f'snios_org{org:04X}{suffix}.cim')

    with open(wrapper, 'w') as f:
        f.write('\t.Z80\n')
        f.write(f'\tORG\t0{org:04X}H\n')
        if defines:
            for k, v in defines.items():
                f.write(f'{k}\tEQU\t{v}\n')
        f.write('\tINCLUDE\tsnios_body.asm\n')

    result = subprocess.run(
        [ZMAC, '-z', '-I', os.path.dirname(src), '-I', outdir,
         wrapper, '-o', cim],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"zmac error (ORG={org:04X}h, defines={defines}):", result.stderr, file=sys.stderr)
        sys.exit(1)

    with open(cim, 'rb') as f:
        data = f.read()

    return data


def build_spr(code, bitmap, outpath):
    """Package code and bitmap into SPR format."""
    code_len = len(code)
    data_len = 0

    # Parameter sector (128 bytes, code/data lengths at offset +1)
    param = bytearray(128)
    param[1] = code_len & 0xFF
    param[2] = (code_len >> 8) & 0xFF
    param[3] = data_len & 0xFF
    param[4] = (data_len >> 8) & 0xFF

    # Data sector (128 bytes, always present, ignored by loader)
    data_sector = bytearray(128)

    # Code + bitmap packed together (padded to 128-byte boundary)
    combined = bytearray(code) + bytearray(bitmap)
    while len(combined) % 128 != 0:
        combined.append(0)

    spr = bytes(param) + bytes(data_sector) + bytes(combined)

    with open(outpath, 'wb') as f:
        f.write(spr)

    return spr


def build_variant(variant_name, defines, filename):
    """Assemble a specific transport variant and build its SPR."""
    suffix = f'_{variant_name.lower()}'
    code_0000 = assemble(SRC, 0x0000, OUTDIR, defines=defines, suffix=suffix)
    code_0100 = assemble(SRC, 0x0100, OUTDIR, defines=defines, suffix=f'{suffix}_hi')

    if len(code_0000) != len(code_0100):
        print(f"Size mismatch ({variant_name}): ORG=0 → {len(code_0000)}, "
              f"ORG=100h → {len(code_0100)}", file=sys.stderr)
        sys.exit(1)

    code_len = len(code_0000)

    # Build relocation bitmap
    bitmap_bits = []
    reloc_count = 0
    for i in range(code_len):
        diff = code_0100[i] - code_0000[i]
        if diff == 1:
            bitmap_bits.append(1)
            reloc_count += 1
        elif diff == 0:
            bitmap_bits.append(0)
        else:
            print(f"WARNING [{variant_name}]: byte {i:04X} differs by {diff} "
                  f"(0x{code_0000[i]:02X} vs 0x{code_0100[i]:02X})",
                  file=sys.stderr)
            bitmap_bits.append(0)

    bitmap_bytes = bytearray()
    for i in range(0, len(bitmap_bits), 8):
        byte = 0
        for j in range(8):
            if i + j < len(bitmap_bits) and bitmap_bits[i + j]:
                byte |= (0x80 >> j)
        bitmap_bytes.append(byte)

    spr_path = os.path.join(OUTDIR, filename)
    spr = build_spr(code_0000, bitmap_bytes, spr_path)

    # In CP/M 2.2, CPNETLDR allocates memory rounded down to 256-byte pages:
    # LDTOP = FREBOT - code_len; LDTOP.L = 0
    pages = math.ceil(code_len / 256)
    alloc_bytes = pages * 256
    snios_base = 0xCC00 - alloc_bytes
    ndos_base = snios_base - 0x0C00  # NDOS takes 12 pages (3072 B)

    print(f"=== Variant: {variant_name} -> {filename} ===")
    print(f"  Code length:      {code_len} bytes (0x{code_len:04X})")
    print(f"  Relocatable bytes: {reloc_count}")
    print(f"  CPNETLDR pages:   {pages} pages ({alloc_bytes} bytes, 0x{alloc_bytes:04X})")
    print(f"  SNIOS in RAM:     0x{snios_base:04X}..0xCBFF")
    print(f"  NDOS in RAM:      0x{ndos_base:04X}..0x{snios_base-1:04X}")
    print(f"  TPA top address:  0x{ndos_base:04X} (TPA size: {ndos_base - 0x0100} B = {(ndos_base - 0x0100)/1024:.2f} KB)")
    print(f"  SPR file size:    {len(spr)} bytes -> {spr_path}\n")

    return spr_path


def main():
    os.makedirs(OUTDIR, exist_ok=True)

    buildinfo = generate_buildinfo(OUTDIR)
    print(f"Build info: {buildinfo}\n")

    # Create body file (snios.asm without ORG directive)
    with open(SRC, 'r') as f:
        lines = f.readlines()

    body_path = os.path.join(OUTDIR, 'snios_body.asm')
    with open(body_path, 'w') as f:
        for line in lines:
            stripped = line.strip().upper()
            if stripped.startswith('ORG') or stripped.startswith('.Z80'):
                continue
            f.write(line)

    # 1. Build SIO variant
    sio_spr = build_variant('SIO', {'TRANSPORT_SIO': 1}, 'SNIOSSIO.SPR')

    # 2. Build PIO variant
    pio_spr = build_variant('PIO', {'TRANSPORT_PIO': 1}, 'SNIOSPIO.SPR')

    # 3. Default SNIOS.SPR is a copy of the SIO variant (primary for MAME)
    default_spr = os.path.join(OUTDIR, 'SNIOS.SPR')
    shutil.copyfile(sio_spr, default_spr)
    print(f"Default SNIOS.SPR -> copied from SNIOSSIO.SPR")

    return 0


if __name__ == '__main__':
    sys.exit(main())
